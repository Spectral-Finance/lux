"""Automated reporting: Markdown reports + CSV export."""
from __future__ import annotations

import csv
import io
from typing import List, Sequence

from .models import AnalyticsSnapshot, VideoMetrics
from .prediction import predict_growth
from .revenue import segment_revenue, estimate_revenue, optimization_tips


def build_report(snapshot: AnalyticsSnapshot, rpm: float = 3.0, forecast_steps: int = 7) -> str:
    ch = snapshot.channel
    # 按发布时间排序后取各视频观看数作为时间序列输入（最新发布的趋势更能反映增长方向）
    views_history = [v.view_count for v in sorted(snapshot.videos, key=lambda v: v.published_at or "")]
    forecast = predict_growth(views_history, forecast_steps) if views_history else []
    seg = segment_revenue(snapshot.videos, rpm)
    tips = optimization_tips(snapshot.videos)
    total_views = ch.view_count or sum(v.view_count for v in snapshot.videos)
    est = estimate_revenue(total_views, rpm)

    lines = [
        f"# YouTube Analytics Report — {ch.title or ch.channel_id}",
        "",
        f"- 频道ID: `{ch.channel_id}`",
        f"- 订阅数: {ch.subscriber_count:,} | 视频数: {ch.video_count:,} | 总观看: {total_views:,}",
        f"- 采集时间: {ch.fetched_at or 'n/a'}",
        "",
        "## 增长预测",
        f"未来 {forecast_steps} 个周期预估观看: " + ", ".join(f"{int(v):,}" for v in forecast) if forecast else "无历史数据",
        "",
        "## 收入估算",
        f"- 按 RPM ${rpm} 估算总观看 {total_views:,} → 毛收入 ${est['gross_usd']}，净收入（55%分成）${est['net_usd']}",
        "",
        "## 单视频表现 Top10",
        "",
        "| 标题 | 观看 | 互动率 | 估算净收入 |",
        "| --- | ---: | ---: | ---: |",
    ]
    for r in seg[:10]:
        lines.append(f"| {r['title'][:60]} | {r['views']:,} | {r['engagement_rate']:.4f} | ${r['estimated_net_usd']} |")
    lines.append("")
    lines.append("## 优化建议")
    for t in tips:
        lines.append(f"- {t}")
    lines.append("")
    lines.append(f"_Generated by YouTube Analytics & Growth Engine (Lux bounty #72)_")
    return "\n".join(lines)


def export_csv(videos: Sequence[VideoMetrics]) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["video_id", "title", "published_at", "views", "likes", "comments", "duration_seconds", "engagement_rate"])
    for v in videos:
        writer.writerow([v.video_id, v.title, v.published_at, v.view_count, v.like_count,
                         v.comment_count, v.duration_seconds, v.engagement_rate])
    return buf.getvalue()

"""Integration tests for the YouTube Analytics & Growth Engine.

Run:  python -m pytest tests/ -v
These tests exercise the full pipeline (collect -> predict -> revenue -> report)
without requiring a YouTube API key (sample data fallback), plus pure-algorithm
unit tests and CSV export checks.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from youtube_analytics import (  # noqa: E402
    YouTubeCollector, predict_growth, linear_regression, exponential_smoothing,
    cmgr, estimate_revenue, segment_revenue, optimization_tips,
    build_report, export_csv,
)
from youtube_analytics.models import AnalyticsSnapshot  # noqa: E402


def test_sample_collect_pipeline():
    col = YouTubeCollector(api_key=None)
    snap = col.collect("UC_sample_channel", max_videos=7)
    assert isinstance(snap, AnalyticsSnapshot)
    assert snap.channel.subscriber_count > 0
    assert len(snap.videos) > 0
    assert all(v.view_count >= 0 for v in snap.videos)
    assert any(c.video_id for c in snap.comments)


def test_linear_regression_exact_line():
    slope, intercept = linear_regression([0, 1, 2, 3], [1, 3, 5, 7])
    assert abs(slope - 2.0) < 1e-9
    assert abs(intercept - 1.0) < 1e-9


def test_predict_linear_extends_trend():
    hist = [10, 20, 30, 40]
    pred = predict_growth(hist, steps=3, method="linear")
    assert len(pred) == 3
    assert pred[0] > 40 and pred[2] > pred[0]


def test_exponential_smoothing_bounds():
    hist = [100, 90, 110, 95, 105]
    pred = exponential_smoothing(hist, alpha=0.3, steps=4)
    assert len(pred) == 4
    assert all(0 <= p <= 200 for p in pred)


def test_cmgr_positive_growth():
    rate = cmgr([100, 121], periods_per_month=1)
    assert abs(rate - 0.21) < 0.01


def test_revenue_estimate():
    est = estimate_revenue(10000, rpm=3.0)
    assert est["gross_usd"] == 30.0
    assert abs(est["net_usd"] - 16.5) < 0.01


def test_segment_revenue_sorted():
    col = YouTubeCollector(api_key=None)
    snap = col.collect("UC_sample_channel", max_videos=7)
    seg = segment_revenue(snap.videos, rpm=3.0)
    assert len(seg) == len(snap.videos)
    nets = [r["estimated_net_usd"] for r in seg]
    assert nets == sorted(nets, reverse=True)


def test_report_contains_key_sections():
    col = YouTubeCollector(api_key=None)
    snap = col.collect("UC_sample_channel", max_videos=7)
    report = build_report(snap, rpm=3.0, forecast_steps=5)
    for section in ["增长预测", "收入估算", "优化建议", "Generated by"]:
        assert section in report


def test_csv_export():
    col = YouTubeCollector(api_key=None)
    snap = col.collect("UC_sample_channel", max_videos=7)
    data = export_csv(snap.videos)
    lines = data.strip().splitlines()
    assert lines[0].startswith("video_id")
    assert len(lines) == len(snap.videos) + 1


def test_sample_data_file_valid():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(here, "youtube_analytics", "sample_data.json"), encoding="utf-8") as fh:
        data = json.load(fh)
    assert data["channel"]["subscriber_count"] > 0
    assert len(data["videos"]) > 0

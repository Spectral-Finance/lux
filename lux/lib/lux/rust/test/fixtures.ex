defmodule Lux.Rust.Test.Fixtures do
  @moduledoc """
  Test fixtures and utilities for Rust-Elixir integration testing.

  Provides helper functions for setting up and tearing down
  Rust test environments, creating temporary Cargo projects,
  and coordinating cross-language test data.
  """

  @doc """
  Creates a temporary Rust project structure for testing.

  Returns `{:ok, project_path}` with a basic Cargo.toml and src/lib.rs.

  ## Examples

      {:ok, path} = Lux.Rust.Test.Fixtures.temp_rust_project()
      assert File.exists?(Path.join(path, "Cargo.toml"))
  """
  @spec temp_rust_project(keyword()) :: {:ok, String.t()} | {:error, String.t()}
  def temp_rust_project(opts \\ []) do
    name = Keyword.get(opts, :name, "lux_test_#{:rand.uniform(99_999)}")
    temp_dir = Keyword.get(opts, :dir, System.tmp_dir!())
    project_path = Path.join(temp_dir, name)

    if File.exists?(project_path) do
      {:error, "Project directory already exists: #{project_path}"}
    else
      File.mkdir_p!(project_path)
      File.mkdir_p!(Path.join(project_path, "src"))

      File.write!(Path.join(project_path, "Cargo.toml"), cargo_toml_content(name))
      File.write!(Path.join(project_path, "src/lib.rs"), "// Generated by Lux.Rust.Test.Fixtures\n")

      {:ok, project_path}
    end
  end

  @doc """
  Executes a callback within a temporary Rust project, then cleans up.

  ## Examples

      Lux.Rust.Test.Fixtures.with_temp_rust_project(fn path ->
        assert File.exists?(Path.join(path, "Cargo.toml"))
        # Do test work...
      end)
  """
  @spec with_temp_rust_project(
          (String.t() -> term()),
          keyword()
        ) :: term()
  def with_temp_rust_project(callback, opts \\ []) do
    {:ok, path} = temp_rust_project(opts)

    try do
      callback.(path)
    after
      File.rm_rf!(path)
    end
  end

  @doc """
  Creates a JSON fixture file for cross-language test data exchange.

  Writes Elixir data to a JSON file that Rust tests can read.

  ## Examples

      Lux.Rust.Test.Fixtures.write_test_data(%{config: %{threshold: 0.5}})
  """
  @spec write_test_data(term(), keyword()) :: {:ok, String.t()} | {:error, String.t()}
  def write_test_data(data, opts \\ []) do
    dir = Keyword.get(opts, :dir, System.tmp_dir!())
    filename = Keyword.get(opts, :filename, "lux_test_#{:rand.uniform(99_999)}.json")
    path = Path.join(dir, filename)

    case Jason.encode(data) do
      {:ok, json} ->
        File.write!(path, json)
        {:ok, path}

      {:error, error} ->
        {:error, "Failed to encode test data: #{inspect(error)}"}
    end
  end

  @doc """
  Reads a JSON test data file produced by Rust tests.

  Returns `{:ok, decoded}` or `{:error, reason}`.
  """
  @spec read_test_data(String.t()) :: {:ok, term()} | {:error, String.t()}
  def read_test_data(path) do
    if File.exists?(path) do
      content = File.read!(path)

      case Jason.decode(content) do
        {:ok, data} -> {:ok, data}
        {:error, error} -> {:error, "Failed to decode test data: #{inspect(error)}"}
      end
    else
      {:error, "Test data file not found: #{path}"}
    end
  end

  @doc """
  Ensures the Rust project is compiled before running tests.
  Returns `:ok` on success, `{:error, reason}` on failure.
  """
  @spec ensure_compiled(String.t()) :: :ok | {:error, String.t()}
  def ensure_compiled(rust_dir) do
    case System.cmd("cargo", ["check"], cd: rust_dir, stderr_to_stdout: true) do
      {_, 0} -> :ok
      {output, code} -> {:error, "Compilation failed (#{code}): #{String.slice(output, 0, 300)}"}
    end
  end

  @doc """
  Runs a cargo command and returns structured output.

  ## Examples

      {:ok, output} = Lux.Rust.Test.Fixtures.run_cargo(["test", "--list"], rust_dir)
  """
  @spec run_cargo([String.t()], String.t()) :: {:ok, String.t()} | {:error, non_neg_integer(), String.t()}
  def run_cargo(args, rust_dir) do
    case System.cmd("cargo", args, cd: rust_dir, stderr_to_stdout: true) do
      {output, 0} -> {:ok, output}
      {output, code} -> {:error, code, output}
    end
  end

  defp cargo_toml_content(name) do
    """
    [package]
    name = "#{name}"
    version = "0.1.0"
    edition = "2021"

    [lib]
    name = "#{name}"

    [dependencies]
    serde = { version = "1.0", features = ["derive"] }
    serde_json = "1.0"
    """
  end
end

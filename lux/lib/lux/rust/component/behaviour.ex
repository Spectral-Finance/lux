defmodule Lux.Rust.Component.Behaviour do
  @moduledoc """
  Behaviour that Rust NIF wrapper modules must implement to integrate
  with the `Lux.Rust.Component` lifecycle.

  Any Elixir module that wraps a compiled Rustler NIF and wishes to
  participate in the Lux component registry should `@behaviour
  Lux.Rust.Component.Behaviour` and implement the three callbacks
  below.

  ## Example

      defmodule MyApp.Prisms.FastMath do
        @behaviour Lux.Rust.Component.Behaviour

        @impl true
        def nif_path, do: Application.app_dir(:my_app, "priv/native/fast_math")

        @impl true
        def nif_functions, do: [:add, :multiply, :fibonacci]

        @impl true
        def handle_call(:add, [a, b]), do: {:ok, a + b}
        def handle_call(:multiply, [a, b]), do: {:ok, a * b}
        def handle_call(name, args), do: {:error, "unknown function #{name} with args #{inspect(args)}"}
      end
  """

  @doc """
  Returns the filesystem path (without extension) to the compiled
  Rustler NIF shared library.

  Rustler loads `<path>.so` on Linux/macOS and `<path>.dll` on Windows.
  Use `Application.app_dir/2` to produce portable paths, e.g.:

      def nif_path, do: Application.app_dir(:my_app, "priv/native/my_nif")
  """
  @callback nif_path() :: String.t()

  @doc """
  Returns the list of atoms naming every NIF function that the shared
  library exports and that this wrapper exposes.

  The list is used by `Lux.Rust.Component` to validate call targets
  before dispatching and to surface introspection data via
  `Lux.Rust.Component.component_info/1`.
  """
  @callback nif_functions() :: [atom()]

  @doc """
  Dispatches a call to `function_name` with the supplied argument list.

  Implementations typically delegate to the raw NIF stub generated by
  Rustler.  The function must return either `{:ok, result}` or
  `{:error, reason}`.

  ## Example

      @impl true
      def handle_call(:fibonacci, [n]) do
        # fibonacci/1 is a raw NIF stub generated by Rustler
        {:ok, fibonacci(n)}
      rescue
        e -> {:error, Exception.message(e)}
      end
  """
  @callback handle_call(function_name :: atom(), args :: list()) ::
              {:ok, term()} | {:error, term()}
end

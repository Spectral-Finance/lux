defmodule Lux.Schemas.TechnicalSignalSchema do
  @moduledoc """
  Schema for technical analysis trading signals generated by the TradingView integration.
  """

  use Lux.SignalSchema,
    name: "technical_signal",
    version: "1.0.0",
    description: "Technical analysis signal combining multiple indicators",
    tags: ["trading", "technical-analysis", "tradingview"],
    schema: %{
      type: :object,
      properties: %{
        symbol: %{
          type: :string,
          description: "Trading symbol (e.g., 'BTC/USDT')"
        },
        timeframe: %{
          type: :string,
          description: "Primary timeframe analyzed"
        },
        signal: %{
          type: :string,
          enum: ["strong_buy", "buy", "hold", "sell", "strong_sell"],
          description: "Overall trading signal"
        },
        confidence: %{
          type: :number,
          minimum: 0,
          maximum: 1,
          description: "Signal confidence score"
        },
        indicators: %{
          type: :object,
          description: "Individual indicator results",
          properties: %{
            rsi: %{
              type: :object,
              properties: %{
                value: %{type: :number},
                signal: %{type: :string}
              }
            },
            macd: %{
              type: :object,
              properties: %{
                macd_line: %{type: :number},
                signal_line: %{type: :number},
                histogram: %{type: :number},
                crossover: %{type: :string}
              }
            },
            bollinger: %{
              type: :object,
              properties: %{
                upper: %{type: :number},
                middle: %{type: :number},
                lower: %{type: :number},
                pct_b: %{type: :number}
              }
            },
            moving_average: %{
              type: :object,
              properties: %{
                sma: %{type: :number},
                ema: %{type: :number},
                trend: %{type: :string}
              }
            }
          }
        },
        timestamp: %{
          type: :string,
          format: "date-time",
          description: "Signal generation timestamp"
        },
        rationale: %{
          type: :string,
          description: "Human-readable explanation of the signal"
        }
      },
      required: ["symbol", "signal", "confidence", "timestamp"]
    }
end
